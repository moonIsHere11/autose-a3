"""Collect real run data from GitHub into results.csv and runs.md.

Usage: python results/collect.py <fork-clone-dir>
Needs `gh` (authenticated). Downloads each autose run's artifacts (status.json, usage.json,
review.json), runs the hidden acceptance tests against every PR branch, and writes:
  results/results.csv   one row per run (issue or seeded PR)
  results/runs.md       links to every Actions run, PR and review
"""
from __future__ import annotations

import csv
import json
import re
import subprocess
import sys
import tempfile
from pathlib import Path

REPO = "moonIsHere11/tinydb-autose"
HERE = Path(__file__).resolve().parent
ROOT = HERE.parent
HIDDEN = ROOT / "experiment" / "hidden_tests"
ISSUE_TESTS = {1: "test_I1_or_query_cache.py", 2: "test_I2_caching_middleware.py", 3: "test_I3_between.py",
               4: "test_I4_upsert_multiple.py", 5: "test_I5_search_isolation.py"}
ISSUE_KIND = {1: "bug", 2: "bug", 3: "feature", 4: "feature", 5: "vague"}
SEEDED = {6: "S1", 7: "S2", 8: "S3", 9: "S4", 10: "S5"}


def gh(*a) -> str:
    return subprocess.run(["gh", *a], capture_output=True, text=True, check=True).stdout


def jget(path: Path):
    return json.loads(path.read_text()) if path.exists() else {}


def hidden(fork: Path, branch: str, issue: int) -> str:
    if issue not in ISSUE_TESTS:
        return ""
    subprocess.run(["git", "-C", str(fork), "fetch", "-q", "origin", branch], check=False)
    with tempfile.TemporaryDirectory() as td:
        subprocess.run(f"git -C {fork} archive FETCH_HEAD tinydb | tar -x -C {td}", shell=True, check=True)
        p = subprocess.run([sys.executable, "-m", "pytest", "-q", "-o", "addopts=", "-p", "no:cacheprovider",
                            str(HIDDEN / ISSUE_TESTS[issue])], cwd=td, capture_output=True, text=True)
        last = (p.stdout.strip().splitlines() or ["?"])[-1]
        return last.split(" in ")[0]


def main(fork: Path):
    runs = json.loads(gh("run", "list", "-R", REPO, "-w", "autose", "-L", "200", "--json",
                         "databaseId,event,displayTitle,conclusion,createdAt,updatedAt,url"))
    rows, md = [], ["# Runs\n", "Every row links to a real GitHub Actions run on the fork. Generated by `results/collect.py`.\n",
                    "| run | trigger | subject | stages | review verdicts | PR | hidden tests | tokens (in/out) | conclusion |",
                    "|---|---|---|---|---|---|---|---|---|"]
    tot_in = tot_out = 0
    for r in sorted(runs, key=lambda x: x["createdAt"]):
        rid = r["databaseId"]
        jobs = json.loads(gh("run", "view", str(rid), "-R", REPO, "--json", "jobs"))["jobs"]
        ran = {j["name"]: j["conclusion"] for j in jobs}
        if ran.get("gate") != "success":
            continue
        with tempfile.TemporaryDirectory() as td:
            t = Path(td)
            arts = json.loads(gh("api", f"repos/{REPO}/actions/runs/{rid}/artifacts?per_page=100"))["artifacts"]
            newest = {}
            for art in sorted(arts, key=lambda x: x["created_at"]):
                base = re.sub(r"-a\d+$", "", art["name"])  # review-1-a2 -> review-1 (ADR-004 attempt suffix)
                newest[base] = art
            for base, art in newest.items():
                z = t / f"{base}.zip"
                with z.open("wb") as fh:
                    subprocess.run(["gh", "api", f"repos/{REPO}/actions/artifacts/{art['id']}/zip"], stdout=fh, check=True)
                subprocess.run(["unzip", "-q", "-o", str(z), "-d", str(t / base)], check=False)
            issue = jget(t / "issue" / "issue.json")
            st0, st1 = jget(t / "work-0" / "status.json"), jget(t / "work-1" / "status.json")
            usage = [jget(p) for p in t.glob("*/usage.json")] + [jget(p).get("usage", {}) for p in t.glob("review-*/review.json")]
            rv = {k: jget(t / k / "review.json") for k in ("review-1", "review-2")}
            pr_md = (t / "release-0" / "pr.md").read_text() if (t / "release-0" / "pr.md").exists() else ""
        u_in = sum(u.get("in", 0) for u in usage)
        u_out = sum(u.get("out", 0) for u in usage)
        tot_in, tot_out = tot_in + u_in, tot_out + u_out
        mode = "review-only" if ran.get("build") == "skipped" else "pipeline"
        num = issue.get("number")
        pr = ""
        if mode == "review-only":
            pr_json = json.loads(gh("pr", "list", "-R", REPO, "--state", "all", "--json", "number,headRefName,title"))
            pr = next((str(p["number"]) for p in pr_json if p["title"] == r["displayTitle"]), "")
        elif "PR: " in pr_md:
            pr = pr_md.rsplit("/pull/", 1)[-1].strip().split()[0]
        stages = {**{k: v["ok"] for k, v in st0.get("stages", {}).items()}}
        stage_str = " ".join(f"{k[:4]}{'✓' if v else '✗'}" for k, v in stages.items())
        verdicts = " / ".join(v.get("verdict", "") for v in rv.values() if v)
        branch = f"autose/issue-{num}" if mode == "pipeline" else ""
        ht = hidden(fork, branch, num) if (mode == "pipeline" and pr) else ""
        variant = "naive" if any("naive" in (v.get("note") or "") for v in rv.values() if v) else "full"
        rows.append({"run_id": rid, "url": r["url"], "mode": mode, "variant": variant, "issue": num,
                     "issue_kind": ISSUE_KIND.get(num, ""), "seeded": SEEDED.get(int(pr), "") if pr.isdigit() else "",
                     "pr": pr, "requirements": stages.get("requirements"), "design": stages.get("design"),
                     "implementation": stages.get("implementation"), "testing": stages.get("testing"),
                     "stopped_at": st0.get("stopped_at") or "", "release": ran.get("ship_0"),
                     "review_1": (rv["review-1"] or {}).get("verdict", ""), "review_1_findings": len((rv["review-1"] or {}).get("findings", [])),
                     "review_1_commands": len((rv["review-1"] or {}).get("runs", [])),
                     "rework_entered_at": st1.get("entered_at", ""), "review_2": (rv["review-2"] or {}).get("verdict", ""),
                     "hidden_tests": ht, "tokens_in": u_in, "tokens_out": u_out, "conclusion": r["conclusion"]})
        prl = f"[#{pr}](https://github.com/{REPO}/pull/{pr})" if pr else "-"
        md.append(f"| [{rid}]({r['url']}) | {r['event']} | {r['displayTitle'][:50]} | {stage_str or mode} | {verdicts or '-'} {('('+variant+')') if verdicts else ''} | {prl} | {ht or '-'} | {u_in}/{u_out} | {r['conclusion']} |")
    with (HERE / "results.csv").open("w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    md.append(f"\n**Total tokens over all runs:** {tot_in:,} input + {tot_out:,} output = {tot_in + tot_out:,}.\n")
    (HERE / "runs.md").write_text("\n".join(md) + "\n")
    print(f"{len(rows)} runs; tokens {tot_in}+{tot_out}")


if __name__ == "__main__":
    main(Path(sys.argv[1]).resolve())
